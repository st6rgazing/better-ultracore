#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const EXPORT_LINE = "if (typeof module !== 'undefined') module.exports = { createEngine, DEFAULT_LIMITS };";
const OUT = path.join(ROOT, 'workflows', 'buc-flow.js');

const HEADER = `export const meta = {
  name: 'buc-flow',
  description: 'better-ultracore: parallel worker fan-out and an optional read-only critic, with hard launch limits',
  whenToUse: 'A task with two or more numbered parts on disjoint files (parallel workers), or /buc deep (one read-only critic on the diff). Not for single edits.',
  phases: [{ title: 'Work' }, { title: 'Critic' }],
};
`;

const ADAPTER = `
const engine = createEngine({ agent, parallel, log, budget });
const res = await engine.run(args || {});
log(\`buc status=\${res.status} launches=\${res.launches}\`);
return res;
`;

function build() {
  const src = fs.readFileSync(path.join(ROOT, 'lib', 'engine.js'), 'utf8').trimEnd().split('\n');
  if (src.pop() !== EXPORT_LINE) throw new Error('lib/engine.js must end with the exact module.exports line');
  return `// Generated by scripts/build-workflow.js from lib/engine.js. Do not edit.\n${HEADER}\n${src.join('\n')}\n${ADAPTER}`;
}

if (require.main === module) {
  const out = build();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== out) {
      console.error('workflows/buc-flow.js is stale: run node scripts/build-workflow.js');
      process.exit(1);
    }
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, out);
  }
}

module.exports = { build };
